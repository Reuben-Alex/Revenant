// PreToolUse guard (Kiro hook "guard-data"). Reads the hook event JSON on stdin.
// Blocks (exit 2) any agent write into public/data/: that folder is produced only by the pipeline,
// so no agent can hand-edit a number the UI will show. Run the pipeline instead.
let raw = '';
process.stdin.on('data', (c) => (raw += c));
process.stdin.on('end', () => {
  let ev = {};
  try { ev = JSON.parse(raw || '{}'); } catch { process.exit(0); }
  const input = ev.tool_input ?? ev.toolInput ?? ev.input ?? ev.arguments ?? {};
  // Check only path fields, so files that merely mention the folder in their content can still be written.
  const pathKeys = ['path', 'targetFile', 'sourcePath', 'destinationPath', 'file_path', 'filePath'];
  const target = pathKeys.map((k) => input?.[k]).filter((v) => typeof v === 'string').join('\n');
  if (/public[\\/]+data[\\/]/i.test(target)) {
    console.error('Blocked: public/data/ is generated by pipeline/ only (see .kiro/steering/honesty.md). Change the pipeline and re-run it.');
    process.exit(2);
  }
  process.exit(0);
});
